const focusSection = (id: string) => {
  const target = document.getElementById(id)
  if (target === null) {
    return
  }
  target.scrollIntoView({ block: 'start' })
  if (!target.hasAttribute('tabindex')) {
    target.setAttribute('tabindex', '-1')
  }
  target.focus({ preventScroll: true })
}

const goToSection = (id: string) => (event: MouseEvent<HTMLAnchorElement>) => {
  event.preventDefault()
  window.location.hash = `/help?section=${id}`
  focusSection(id)
}

const SectionLink = ({ sectionId, children }: { sectionId: string; children: ReactNode }) => (
  <a href={`#/help?section=${sectionId}`} onClick={goToSection(sectionId)}>{children}</a>
)

