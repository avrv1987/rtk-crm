export const rolesFor = (modules: Modules): Role[] => allRoles
  .filter((role) => role.module === undefined || modules[role.module])
  .map((role) => ({ ...role, duties: role.duties.filter((duty) => duty !== partnerAccessDuty || modules.partner) }))

