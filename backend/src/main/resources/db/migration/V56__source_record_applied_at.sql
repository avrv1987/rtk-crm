-- Время первого применения записи источника. «Заявка с сайта» (почта и MAX) отбирается по нему: заявку неизвестного
-- вуза применяют после сопоставления, и время создания записи к этому моменту уже вне окна сборщика. Для уже
-- применённых записей берётся время создания, чтобы после обновления не пришли письма по старым заявкам.
ALTER TABLE source_records ADD COLUMN applied_at TIMESTAMP WITH TIME ZONE;
UPDATE source_records SET applied_at = created_at WHERE status = 'APPLIED';
