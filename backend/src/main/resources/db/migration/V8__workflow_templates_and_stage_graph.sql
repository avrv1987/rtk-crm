CREATE TABLE workflow_templates (
    id UUID PRIMARY KEY,
    team_id UUID REFERENCES teams(id),
    name VARCHAR(200) NOT NULL,
    default_template BOOLEAN NOT NULL DEFAULT FALSE,
    version INTEGER NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX workflow_templates_default_idx
    ON workflow_templates (default_template)
    WHERE default_template;

CREATE INDEX workflow_templates_team_name_idx
    ON workflow_templates (team_id, name, id);

CREATE TABLE workflow_template_stages (
    id UUID PRIMARY KEY,
    template_id UUID NOT NULL REFERENCES workflow_templates(id) ON DELETE CASCADE,
    stage_order INTEGER NOT NULL CHECK (stage_order >= 0),
    name VARCHAR(200) NOT NULL,
    optional BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT workflow_template_stages_order_key UNIQUE (template_id, stage_order),
    CONSTRAINT workflow_template_stages_id_template_key UNIQUE (id, template_id)
);

CREATE TABLE workflow_template_transitions (
    template_id UUID NOT NULL REFERENCES workflow_templates(id) ON DELETE CASCADE,
    from_stage_id UUID NOT NULL,
    to_stage_id UUID NOT NULL,
    comment_required BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (template_id, from_stage_id, to_stage_id),
    FOREIGN KEY (from_stage_id, template_id)
        REFERENCES workflow_template_stages(id, template_id) ON DELETE CASCADE,
    FOREIGN KEY (to_stage_id, template_id)
        REFERENCES workflow_template_stages(id, template_id) ON DELETE CASCADE,
    CHECK (from_stage_id <> to_stage_id)
);

CREATE TABLE interaction_stage_transitions (
    interaction_id UUID NOT NULL REFERENCES interactions(id) ON DELETE CASCADE,
    from_stage_id UUID NOT NULL,
    to_stage_id UUID NOT NULL,
    comment_required BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (interaction_id, from_stage_id, to_stage_id),
    FOREIGN KEY (from_stage_id, interaction_id)
        REFERENCES interaction_stages(id, interaction_id) ON DELETE CASCADE,
    FOREIGN KEY (to_stage_id, interaction_id)
        REFERENCES interaction_stages(id, interaction_id) ON DELETE CASCADE,
    CHECK (from_stage_id <> to_stage_id)
);

